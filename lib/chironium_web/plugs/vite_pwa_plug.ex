defmodule ChironiumWeb.VitePwaPlug do
  @moduledoc """
  Development-only plug for proxying Vite PWA assets from the dev server.

  Intercepts requests for service worker and workbox files generated by
  vite-plugin-pwa and proxies them from the Vite dev server to Phoenix.

  ## Matched patterns

  - `/dev-sw.js` and `/dev-sw.js.map` - Service worker files
  - `/workbox-{hash}.js` and `/workbox-{hash}.js.map` - Workbox runtime files

  ## Why a Plug in the Endpoint?

  This plug is registered in `ChironiumWeb.Endpoint` rather than the router because:

  1. Phoenix router doesn't support dynamic path segments with hyphens
     (e.g., `workbox-abc123.js` triggers `Plug.Router.InvalidSpecError`)
  2. Endpoint plugs run before the router, allowing early interception
  3. Follows Phoenix conventions where static/proxy assets are handled at endpoint level

  ## Production

  This plug is only active in development when `code_reloading?` is true.
  In production, PWA files are built into `priv/static/` and served by `Plug.Static`.
  """

  import Plug.Conn
  require Logger

  @behaviour Plug

  @impl true
  def init(opts), do: opts

  @impl true
  def call(conn, _opts) do
    if pwa_file?(conn.request_path) do
      proxy_to_vite(conn)
    else
      conn
    end
  end

  defp pwa_file?(path) do
    String.match?(path, ~r{^/(dev-sw|workbox-[a-f0-9]+)\.(js|js\.map)$})
  end

  defp proxy_to_vite(conn) do
    path = conn.request_path

    url =
      case local_dev_server_url() do
        {:ok, base_url} ->
          base_url
          |> URI.merge(path)
          |> URI.to_string()
          |> maybe_add_query(conn.query_string)

        {:error, reason} ->
          Logger.error("Invalid Vite dev server URL: #{inspect(reason)}")

          return_early(conn, 502, "Vite dev server unavailable.")
      end

    Logger.debug("Proxying Vite PWA asset: #{path} -> #{url}")

    case Req.get(url, retry: false, max_redirects: 0) do
      {:ok, %{status: 200, body: body, headers: headers}} ->
        content_type = get_content_type(headers, path)

        if allowed_content_type?(content_type, path) do
          conn =
            conn
            |> put_resp_header("content-type", content_type)
            |> put_resp_header("cache-control", "no-store, no-cache, must-revalidate")
            |> put_resp_header("service-worker-allowed", "/")
            |> put_resp_header("x-content-type-options", "nosniff")
            |> put_resp_header("x-proxied-from", "vite-dev-server")

          conn
          |> send_resp(200, body)
          |> halt()
        else
          Logger.warning(
            "Vite dev server returned unexpected content type #{inspect(content_type)} for #{path}"
          )

          return_early(conn, 502, "Vite dev server returned unexpected content.")
        end

      {:ok, %{status: status, body: body}} ->
        Logger.warning("Vite dev server returned #{status} for #{path}: #{inspect(body)}")

        return_early(conn, status, "Vite dev server returned #{status}.")

      {:error, reason} ->
        Logger.error("Failed to proxy #{path} from Vite: #{inspect(reason)}")

        return_early(conn, 502, "Vite dev server unavailable.")
    end
  end

  defp maybe_add_query(url, ""), do: url
  defp maybe_add_query(url, query), do: "#{url}?#{query}"

  defp get_content_type(headers, path) do
    headers
    |> Enum.find_value(fn {key, value} ->
      if String.downcase(key) == "content-type", do: value
    end)
    |> normalize_content_type(path)
  end

  defp normalize_content_type(nil, path), do: guess_content_type(path)

  defp normalize_content_type(value, path) when is_list(value) do
    case value do
      [first | _rest] -> normalize_content_type(first, path)
      _ -> guess_content_type(path)
    end
  end

  defp normalize_content_type(value, _path) when is_binary(value), do: value

  defp guess_content_type(path) do
    cond do
      String.ends_with?(path, ".js") -> "application/javascript"
      String.ends_with?(path, ".map") -> "application/json"
      String.ends_with?(path, ".css") -> "text/css"
      String.ends_with?(path, ".html") -> "text/html"
      true -> "application/octet-stream"
    end
  end

  defp allowed_content_type?(content_type, path) when is_binary(content_type) do
    normalized =
      content_type
      |> String.split(";")
      |> List.first()
      |> String.trim()
      |> String.downcase()

    case Path.extname(path) do
      ".js" -> normalized in ["application/javascript", "text/javascript"]
      ".map" -> normalized in ["application/json"]
      _ -> false
    end
  end

  defp allowed_content_type?(_, _), do: false

  defp local_dev_server_url do
    url = dev_server_url()

    case URI.parse(url) do
      %URI{scheme: scheme, host: host}
      when scheme in ["http", "https"] and host in ["localhost", "127.0.0.1", "::1"] ->
        {:ok, url}

      %URI{scheme: scheme, host: host} ->
        {:error, {:disallowed_host, scheme, host}}

      _ ->
        {:error, :invalid_url}
    end
  end

  defp return_early(conn, status, message) do
    conn
    |> put_resp_header("content-type", "text/plain; charset=utf-8")
    |> put_resp_header("x-content-type-options", "nosniff")
    |> send_resp(status, message)
    |> halt()
  end

  defp dev_server_url do
    endpoint_config = Application.get_env(:chironium, ChironiumWeb.Endpoint, [])
    static_url = Keyword.get(endpoint_config, :static_url, [])
    scheme = Keyword.get(static_url, :scheme, "http")
    host = Keyword.get(static_url, :host, "localhost")
    port = Keyword.get(static_url, :port, 5173)

    "#{scheme}://#{host}:#{port}"
  end
end
