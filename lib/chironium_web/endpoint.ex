defmodule ChironiumWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :chironium
  use Absinthe.Phoenix.Endpoint
  import PhoenixVite.Plug

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_chironium_key",
    signing_salt: "p2O2GnCc",
    # Security: Prevent JavaScript access to session cookie.
    http_only: true,
    # Security: Only send cookie over HTTPS in production.
    secure: Mix.env() == :prod,
    # Security: Prevent CSRF via cross-site requests.
    same_site: "Lax",
    # Session expires after 14 days of inactivity.
    max_age: 60 * 60 * 24 * 14
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  socket "/ws/gql", ChironiumWeb.GraphqlSocket, websocket: true, longpoll: true

  plug :favicon, dev_server: {PhoenixVite.Components, :has_vite_watcher?, [__MODULE__]}

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :chironium,
    gzip: not code_reloading?,
    only: ChironiumWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug ChironiumWeb.Plugs.CheckCodegenStatus
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :chironium
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json, Absinthe.Plug.Parser],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options

  # Dev-only: Proxy Vite assets (i18n locales).
  # Must be placed before Router to intercept requests early.
  if code_reloading? do
    plug ChironiumWeb.ViteDevProxyPlug
  end

  plug ChironiumWeb.Router
end
