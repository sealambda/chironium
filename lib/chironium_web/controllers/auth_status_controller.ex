defmodule ChironiumWeb.AuthStatusController do
  @moduledoc """
  Controller for authentication status endpoints.

  Provides endpoints for the React SPA to check auth status and get current user info.
  This controller is used by the frontend to determine if a user is authenticated
  and to retrieve their profile information.

  The response format follows JSON:API specification for consistency with the rest
  of the API, though this endpoint is not generated by ash_json_api.
  """
  use ChironiumWeb, :controller

  @doc """
  Returns the currently authenticated user or 401 if not authenticated.

  Used by the React SPA to check session status on page load and after OAuth callbacks.
  The user is loaded from the conn assigns, which is set by the :load_from_bearer plug
  in the :api pipeline.

  ## Response

  - 200 OK with user JSON:API response if authenticated.
  - 401 Unauthorized with error JSON:API response if no valid session/token.
  """
  @spec me(Plug.Conn.t(), map()) :: Plug.Conn.t()
  def me(conn, _params) do
    case conn.assigns[:current_user] do
      nil ->
        conn
        |> put_status(:unauthorized)
        |> json(%{
          errors: [
            %{
              status: "401",
              title: "Unauthorized",
              detail: "Not authenticated"
            }
          ]
        })

      user ->
        # Load person relationship for display name.
        user_with_person =
          case Ash.load(user, [:person]) do
            {:ok, loaded_user} -> loaded_user
            _ -> user
          end

        conn
        |> put_status(:ok)
        |> json(%{
          data: %{
            id: user_with_person.id,
            type: "user",
            attributes: %{
              email: user_with_person.email,
              person: format_person(user_with_person.person)
            }
          }
        })
    end
  end

  # Format person data for JSON response.
  # Returns nil if no person is associated.
  defp format_person(nil), do: nil

  defp format_person(person) do
    %{
      id: person.id,
      given_name: person.given_name,
      st_surname: person.st_surname,
      nd_surname: person.nd_surname
    }
  end
end
