import { marked } from "marked";
import { useMemo } from "react";

import { cn } from "@/shared/utils/utils";

marked.setOptions({
  breaks: true,
  gfm: true,
});

interface MarkdownContentProps {
  readonly content: string;
  readonly className?: string;
}

/**
 * Renders a markdown string as styled HTML.
 * Uses `marked` for parsing and Tailwind utilities for typography.
 */
export function MarkdownContent({ content, className }: MarkdownContentProps) {
  const html = useMemo(() => {
    if (!content) {
      return "";
    }
    return marked.parse(content, { async: false });
  }, [content]);

  if (!html) {
    return null;
  }

  return (
    <div
      className={cn(
        "markdown-content text-foreground/80 text-sm leading-relaxed",
        "[&_h1]:mt-4 [&_h1]:mb-2 [&_h1]:font-semibold [&_h1]:text-base [&_h1]:text-foreground",
        "[&_h2]:mt-3 [&_h2]:mb-1.5 [&_h2]:font-semibold [&_h2]:text-foreground [&_h2]:text-sm",
        "[&_h3]:mt-2 [&_h3]:mb-1 [&_h3]:font-medium [&_h3]:text-foreground [&_h3]:text-sm",
        "[&_p:last-child]:mb-0 [&_p]:mb-2",
        "[&_ul]:mb-2 [&_ul]:list-disc [&_ul]:pl-5",
        "[&_ol]:mb-2 [&_ol]:list-decimal [&_ol]:pl-5",
        "[&_li]:mb-0.5",
        "[&_strong]:font-semibold [&_strong]:text-foreground",
        "[&_em]:italic",
        "[&_code]:rounded [&_code]:bg-muted [&_code]:px-1 [&_code]:py-0.5 [&_code]:font-mono [&_code]:text-xs",
        "[&_blockquote]:border-neutral-300 [&_blockquote]:border-l-2 [&_blockquote]:pl-3 [&_blockquote]:text-foreground/60 [&_blockquote]:italic",
        className,
      )}
      // Content is generated by marked from user-authored markdown.
      // biome-ignore lint/security/noDangerouslySetInnerHtml: sanitized markdown output
      dangerouslySetInnerHTML={{ __html: html }}
    />
  );
}
